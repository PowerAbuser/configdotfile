    backdrop 5 0.6 0.3
    label "$(clock)" "$ui" 140 "$(c "$ink")" 0 140 center center
    label "$(date_line '%A, %-d %B')" "$ui" 18 "$(c "$dim")" 0 20 center center
    field 280 -1 "breathe" "again, slowly" "$ui" 0 -90 center center ;;

